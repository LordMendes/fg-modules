import type { FiveRoomMotif } from "./types";
import { FIVE_ROOM_MOTIFS } from "./types";

export type TaggedPhrase = {
  motif: FiveRoomMotif;
  text: string;
};

type MotifBank = Record<Exclude<FiveRoomMotif, "none">, string[]>;

function bank(
  entries: Record<Exclude<FiveRoomMotif, "none">, string[]>,
): MotifBank {
  for (const motif of FIVE_ROOM_MOTIFS) {
    if (motif === "none") continue;
    const list = entries[motif];
    if (!list || list.length < 8) {
      throw new Error(`five-room tables: ${motif} needs at least 8 entries`);
    }
  }
  return entries;
}


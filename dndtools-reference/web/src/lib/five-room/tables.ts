const MOTIFS_WITH_LISTS = FIVE_ROOM_MOTIFS.filter(
  (m): m is Exclude<FiveRoomMotif, "none"> => m !== "none",
);

export function taggedPool(
  bankTable: MotifBank,
  motif: FiveRoomMotif,
): TaggedPhrase[] {
  if (motif === "none") {
    return MOTIFS_WITH_LISTS.flatMap((m) =>
      bankTable[m].map((text) => ({ motif: m, text })),
    );
  }
  return bankTable[motif].map((text) => ({ motif, text }));
}

export function pickTaggedPhrase(
  bankTable: MotifBank,
  motif: FiveRoomMotif,
  rng: { pick: <T>(items: T[]) => T | undefined },
): TaggedPhrase {
  const pool = taggedPool(bankTable, motif);
  return rng.pick(pool) ?? pool[0]!;
}

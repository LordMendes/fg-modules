import type { FractalPalette, SurfaceKind } from "./types";

export type Rgb = readonly [number, number, number];

/** Bathymetry, lowland, highland, ice. Hex allowed in this data file only. */
export const PALETTE_STOPS: Record<FractalPalette, readonly [Rgb, Rgb, Rgb, Rgb]> =
  {
    atlas: [
      [0x0a, 0x3d, 0x62],
      [0x3a, 0x8c, 0x4a],
      [0x8b, 0x5a, 0x2b],
      [0xf5, 0xf5, 0xf0],
    ],
    antique: [
      [0x2e, 0x3a, 0x6b],
      [0x6b, 0x7a, 0x3a],
      [0xc4, 0xa4, 0x6a],
      [0xf0, 0xe6, 0xd2],
    ],
    barren: [
      [0x6a, 0x7a, 0x8a],
      [0xc4, 0xb4, 0x8a],
      [0xa0, 0x5a, 0x3a],
      [0xe8, 0xdc, 0xc8],
    ],
    martian: [
      [0x1a, 0x08, 0x08],
      [0x8b, 0x3a, 0x2a],
      [0xc4, 0x6a, 0x2a],
      [0xe8, 0xc4, 0x9a],
    ],
    chthonian: [
      [0x0a, 0x0a, 0x0a],
      [0x4a, 0x12, 0x12],
      [0x8a, 0x3a, 0x18],
      [0x5a, 0x52, 0x48],
    ],
    greyscale: [
      [0x28, 0x28, 0x28],
      [0x78, 0x78, 0x78],
      [0xa8, 0xa8, 0xa8],
      [0xe0, 0xe0, 0xe0],
    ],
    landmask: [
      [0x00, 0x00, 0x00],
      [0xff, 0xff, 0xff],
      [0xff, 0xff, 0xff],
      [0xcc, 0xcc, 0xcc],
    ],
  };

export function colorForSurface(
  palette: FractalPalette,
  kind: SurfaceKind,
): Rgb {
  const stops = PALETTE_STOPS[palette];
  switch (kind) {
    case "sea":
      return stops[0];
    case "lowland":
      return stops[1];
    case "highland":
      return stops[2];
    case "ice":
      return stops[3];
  }
}
